#!/usr/bin/env node
// Turns design/tokens.json into CSS variables for light and dark.
// Output: apps/web/src/styles/tokens.css (committed, never edited by hand).
// Usage:
//   node scripts/build-tokens.mjs           write the file
//   node scripts/build-tokens.mjs --check   fail if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "design", "tokens.json");
const target = join(root, "apps", "web", "src", "styles", "tokens.css");

// Families that next/font loads. next/font sets these variables on <html>.
// The name after the comma is the plain fallback if the variable is missing.
const LOADED_FONTS = {
  Arimo: "--next-font-arimo",
  Quicksand: "--next-font-quicksand",
};

const tokens = JSON.parse(readFileSync(source, "utf8"));

const colorRef = (value) => value.replace(/\{([\w-]+)\}/g, (_, name) => `var(--color-${name})`);

function fontStack(stack) {
  return stack
    .split(",")
    .map((part) => part.trim())
    .map((family) => {
      const variable = LOADED_FONTS[family];
      return variable ? `var(${variable}, ${family})` : family;
    })
    .join(", ");
}

const light = [];
const dark = [];
const alias = [];
const fixed = [];

for (const token of tokens.color.tokens) {
  const name = `--color-${token.name}`;
  if (typeof token.value === "string" && token.value.startsWith("{")) {
    alias.push(`${name}: ${colorRef(token.value)};`);
  } else if (typeof token.value === "string") {
    fixed.push(`${name}: ${token.value};`);
  } else {
    light.push(`${name}: ${token.value.light};`);
    dark.push(`${name}: ${token.value.dark};`);
  }
}

const font = Object.entries(tokens.type.families).map(
  ([name, stack]) => `--font-${name}: ${fontStack(stack)};`,
);

const type = [];
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    const family = style.family ?? group.family;
    type.push(
      `--type-${style.name}-family: var(--font-${family});`,
      `--type-${style.name}-size: ${style.fontSize};`,
      `--type-${style.name}-line: ${style.lineHeight};`,
      `--type-${style.name}-weight: ${style.fontWeight};`,
      `--type-${style.name}-tracking: ${style.letterSpacing ?? "normal"};`,
    );
  }
}

const simple = (list) => list.tokens.map((token) => `--${token.name}: ${token.value};`);

const spacing = simple(tokens.spacing);
const radius = simple(tokens.radius);
const shadow = simple(tokens.shadow);
const duration = simple(tokens.duration);
const easing = simple(tokens.easing);

const block = (selector, lines, indent = "") =>
  [
    `${indent}${selector} {`,
    ...lines.map((line) => (line ? `${indent}  ${line}` : "")),
    `${indent}}`,
  ].join("\n");

const css = `${[
  "/*",
  " * Generated by scripts/build-tokens.mjs from design/tokens.json.",
  " * Do not edit by hand. Change the tokens file, then run: node scripts/build-tokens.mjs",
  " *",
  " * Light is the default. Dark follows the visitor's system setting (prefers-color-scheme).",
  ' * <html data-theme="light"> or data-theme="dark" forces one theme. Nothing sets it today.',
  " * Dark swaps colour tokens and changes nothing else.",
  " */",
  "",
  block(":root", [
    "color-scheme: light;",
    ...light,
    ...alias,
    "",
    "/* Fixed brand colours, the same in both themes */",
    ...fixed,
    "",
    ...font,
    "",
    ...type,
    "",
    ...spacing,
    "",
    ...radius,
    "",
    ...shadow,
    "",
    ...duration,
    ...easing,
  ]),
  "",
  "@media (prefers-color-scheme: dark) {",
  block(':root:not([data-theme="light"])', ["color-scheme: dark;", ...dark], "  "),
  "}",
  "",
  block(':root[data-theme="dark"]', ["color-scheme: dark;", ...dark]),
  "",
  "/* Motion changes state only, and drops to zero for visitors who ask for less motion. */",
  "@media (prefers-reduced-motion: reduce) {",
  block(
    ":root",
    tokens.duration.tokens.map((token) => `--${token.name}: 0ms;`),
    "  ",
  ),
  "}",
].join("\n")}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // A missing file counts as out of date.
  }
  if (current !== css) {
    console.error(
      "build-tokens: apps/web/src/styles/tokens.css is out of date. Run: node scripts/build-tokens.mjs",
    );
    process.exit(1);
  }
  console.log("build-tokens: tokens.css matches design/tokens.json");
} else {
  writeFileSync(target, css);
  console.log("build-tokens: wrote apps/web/src/styles/tokens.css");
}
